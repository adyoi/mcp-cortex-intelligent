import * as fs from "fs";
import * as path from "path";
import * as db from "../db/database.js";
import { createHash } from "node:crypto";
import { provision } from "../provisioner/marker-block.js";

function tid(): string {
  return "task-" + createHash("sha256").update(String(Date.now()) + Math.random()).digest("hex").slice(0, 8);
}

export function initPlan(projectRoot: string): { created: boolean; path: string } {
  const p = path.join(projectRoot, "PLAN.md");
  if (fs.existsSync(p)) return { created: false, path: p };
  const skeleton = "# PLAN\n\n> Auto-generated by mcp-cortex-intelligent.\n\n## 1. Goal\n\n(describe the goal)\n\n## 2. Steps\n\n- Step 1\n- Step 2\n";
  fs.mkdirSync(projectRoot, { recursive: true });
  fs.writeFileSync(p, skeleton);
  return { created: true, path: p };
}

export function readPlan(projectRoot: string, full = true): { content: string; exists: boolean } {
  const p = path.join(projectRoot, "PLAN.md");
  if (!fs.existsSync(p)) return { content: "", exists: false };
  const content = fs.readFileSync(p, "utf8");
  if (full) return { content, exists: true };
  const headings = content.split(/\r?\n/).filter(l => /^#{1,6}\s/.test(l));
  return { content: headings.join("\n"), exists: true };
}

export function updatePlanSection(projectRoot: string, heading: string, content: string): { updated: boolean } {
  const p = path.join(projectRoot, "PLAN.md");
  if (!fs.existsSync(p)) return { updated: false };
  let text = fs.readFileSync(p, "utf8");
  const lines = text.split(/\r?\n/);
  const idx = lines.findIndex(l => l.trim() === heading.trim() || l.trim().replace(/^#+\s*/, "") === heading.trim().replace(/^#+\s*/, ""));
  if (idx === -1) return { updated: false };
  const level = (lines[idx].match(/^#+/) || [""])[0].length || 2;
  let end = lines.length;
  for (let i = idx + 1; i < lines.length; i++) {
    const m = lines[i].match(/^#+/);
    if (m && m[0].length <= level) { end = i; break; }
  }
  const newLines = [...lines.slice(0, idx + 1), content, ...lines.slice(end)];
  fs.writeFileSync(p, newLines.join("\n"));
  return { updated: true };
}

