export function taskCreate(title: string, planRef?: string, priority = 0, owner?: string): { id: string } {
  const id = tid();
  db.getDB().prepare(
    "INSERT INTO tasks (id, plan_ref, title, status, priority, owner, notes, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?)"
  ).run(id, planRef ?? null, title, "todo", priority, owner ?? null, "", Date.now(), Date.now());
  return { id };
}

export function taskList(filter: { status?: string; priority?: number; limit?: number; offset?: number } = {}): any[] {
  let sql = "SELECT * FROM tasks WHERE 1=1";
  const params: any[] = [];
  if (filter.status) { sql += " AND status = ?"; params.push(filter.status); }
  if (filter.priority !== undefined) { sql += " AND priority = ?"; params.push(filter.priority); }
  sql += " ORDER BY priority DESC, created_at ASC, id ASC";
  const limit = Math.min(Math.max(Math.trunc(filter.limit ?? TASK_LIST_DEFAULT), 1), TASK_LIST_MAX);
  const offset = Math.max(Math.trunc(filter.offset ?? 0), 0);
  sql += " LIMIT ? OFFSET ?";
  params.push(limit, offset);
  return db.getDB().prepare(sql).all(...params) as any[];
}

/** Total matching rows for a taskList filter (pagination bookkeeping). */
export function taskCount(filter: { status?: string; priority?: number } = {}): number {
  let sql = "SELECT COUNT(*) AS c FROM tasks WHERE 1=1";
  const params: any[] = [];
  if (filter.status) { sql += " AND status = ?"; params.push(filter.status); }
  if (filter.priority !== undefined) { sql += " AND priority = ?"; params.push(filter.priority); }
  return (db.getDB().prepare(sql).get(...params) as { c: number }).c;
}

export function taskGet(id: string): any {
  return db.getDB().prepare("SELECT * FROM tasks WHERE id = ?").get(id);
}

export function taskStart(id: string): { ok: boolean } {
  const r = db.getDB().prepare("UPDATE tasks SET status='doing', updated_at=? WHERE id=?").run(Date.now(), id);
  return { ok: r.changes > 0 };
}

export function taskDone(id: string): { ok: boolean } {
  const r = db.getDB().prepare("UPDATE tasks SET status='done', updated_at=?, done_at=? WHERE id=?").run(Date.now(), Date.now(), id);
  return { ok: r.changes > 0 };
}

export function taskUpdate(id: string, patch: { title?: string; priority?: number; owner?: string; plan_ref?: string; notes?: string }): { ok: boolean } {
  const t = taskGet(id);
  if (!t) return { ok: false };
  const title = patch.title ?? t.title;
  const priority = patch.priority ?? t.priority;
  const owner = patch.owner ?? t.owner;
  const plan_ref = patch.plan_ref ?? t.plan_ref;
  const notes = patch.notes ?? t.notes;
  const r = db.getDB().prepare("UPDATE tasks SET title=?, priority=?, owner=?, plan_ref=?, notes=?, updated_at=? WHERE id=?").run(title, priority, owner, plan_ref, notes, Date.now(), id);
  return { ok: r.changes > 0 };
}

export function taskBlock(id: string, reason: string): { ok: boolean } {
  const t = taskGet(id);
  const notes = t ? `${t.notes || ""}\nBlocked: ${reason}`.trim() : `Blocked: ${reason}`;
  const r = db.getDB().prepare("UPDATE tasks SET status='blocked', notes=?, updated_at=? WHERE id=?").run(notes, Date.now(), id);
  return { ok: r.changes > 0 };
}

export function taskDelete(id: string): { ok: boolean } {
  const r = db.getDB().prepare("DELETE FROM tasks WHERE id=?").run(id);
  return { ok: r.changes > 0 };
}

export function taskSummary(): { total: number; todo: number; doing: number; done: number; blocked: number } {
  const rows = db.getDB().prepare("SELECT status, COUNT(*) AS c FROM tasks GROUP BY status").all() as any[];
  const m: any = { todo: 0, doing: 0, done: 0, blocked: 0 };
  let total = 0;
  for (const r of rows) { m[r.status] = r.c; total += r.c; }
  return { total, todo: m.todo, doing: m.doing, done: m.done, blocked: m.blocked };
}

export function taskSyncMd(projectRoot: string): { path: string } {
  const p = path.join(projectRoot, "TASK.md");
  const tasks = taskList({ limit: TASK_LIST_MAX });
  const groups: Record<string, any[]> = { todo: [], doing: [], done: [], blocked: [] };
  for (const t of tasks) {
    if (!groups[t.status]) groups[t.status] = [];
    groups[t.status].push(t);
  }
  const lines: string[] = [];
  lines.push("# TASK");
  lines.push("");
  lines.push("> Managed by mcp-cortex-intelligent.");
  lines.push("");
  for (const status of ["todo", "doing", "done", "blocked"]) {
    lines.push(`## ${status.charAt(0).toUpperCase() + status.slice(1)}`);
    lines.push("");
    for (const t of groups[status] || []) {
      const check = status === "done" ? "[x]" : "[ ]";
      lines.push(`- ${check} ${t.id}: ${t.title}`);
    }
    lines.push("");
  }
  const autoBlock = lines.join("\n");
  fs.mkdirSync(projectRoot, { recursive: true });
  provision(p, autoBlock, "task-sync");
  return { path: p };
}


export function taskFromPlan(projectRoot: string): { created: number; ids: string[] } {
  const planPath = path.join(projectRoot, "PLAN.md");
  if (!fs.existsSync(planPath)) return { created: 0, ids: [] };
  const lines = fs.readFileSync(planPath, "utf8").split(/\r?\n/);
  // Collect bullet/numbered lines under a "Steps"/"Tasks"/"Plan" heading.
  const ids: string[] = [];
  let inSection = false;
  for (const raw of lines) {
    const line = raw.trim();
    if (/^#{1,6}\s/.test(line)) { inSection = /step|task|plan|todo/i.test(line); continue; }
    if (!inSection) continue;
    const m = line.match(/^[-*]\s+(.+)$/) || line.match(/^\d+\.\s+(.+)$/);
    if (!m) continue;
    const title = m[1].trim();
    if (title.length < 3) continue;
    const r = taskCreate(title, "PLAN.md");
    ids.push(r.id);
  }
  return { created: ids.length, ids };
}
